  static int color(EventState.Kind kind) {
    return switch (kind) {
      case RAID -> 0xFFFF9F6E;
      case MEGA -> 0xFFCF9EFF;
      case SHINY -> 0xFFFFDA70;
      case XP -> 0xFF81DBFF;
      case IV -> 0xFF79E4B7;
      case ABILITY -> 0xFFF2A4D1;
      case CLEAR -> 0xFFE9B87A;
      case SEASON -> 0xFF86E0D5;
    };
  }

  static void draw(DrawContext c, EventState.Kind kind, int x, int y, int scale) {
    var rows = GLYPHS[kind.ordinal()];
    int color = color(kind);
    for (int row = 0; row < 12; row++)
      for (int col = 0; col < 12; col++)
        if (rows[row].charAt(col) == '1')
          c.fill(
              x + col * scale,
              y + row * scale,
              x + (col + 1) * scale,
              y + (row + 1) * scale,
              color);
  }
